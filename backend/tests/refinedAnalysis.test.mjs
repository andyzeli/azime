test("classification covers applicability/adequacy combinations for original and physician-added treatments", () => {
  const cases = [
    ["applicable", "adequately_trialed", "context"],
    ["applicable", "inadequately_trialed", "issue"],
    ["applicable", "not_tried", "issue"],
    ["applicable", "unclear", "issue"],
    ["unclear", "adequately_trialed", "issue"],
    ["unclear", "inadequately_trialed", "issue"],
    ["unclear", "not_tried", "issue"],
    ["unclear", "unclear", "issue"],
    ["not_applicable", "adequately_trialed", "omit"],
    ["not_applicable", "inadequately_trialed", "omit"],
    ["not_applicable", "not_tried", "omit"],
    ["not_applicable", "unclear", "omit"],
    ["contraIndicated", "adequately_trialed", "omit"],
    ["contraIndicated", "inadequately_trialed", "omit"],
    ["contraIndicated", "not_tried", "omit"],
    ["contraIndicated", "unclear", "omit"],
  ];
  for (const source of ["original", "physician"]) {
    for (const [applicability, adequacy, expected] of cases) {
      const args = fixture();
      if (source === "original") {
        // Classify physician overrides, not the original AI judgments.
        args.preExam.analysis.treatmentAnalysis[0].assessments.splice(1);
        args.steering.steering.treatments[rowId] = {
          assessments: {
            strain: {
              applicability: {
                action: "override",
                value: applicability,
                rationale: "Effective applicability",
              },
              adequacy: {
                action: "override",
                value: adequacy,
                rationale: "Effective adequacy",
              },
            },
          },
        };
      } else {
        args.preExam.analysis.treatmentAnalysis = [];
        args.steering.steering.addedTreatments = [
          {
            id: addedId,
            treatmentId: null,
            treatment: "Physician option",
            category: "conservative",
            episodeIds: [],
            assessments: {
              strain: {
                applicability,
                adequacy,
                rationale: "Physician judgment",
              },
            },
          },
        ];
      }
      const review =
        buildRefinedAnalysisInputSnapshot(args).input.reviewedAnalysis;
      const message = `${source}: ${applicability}, ${adequacy}`;
      assert.equal(
        review.treatmentIssues.length,
        expected === "issue" ? 1 : 0,
        message,
      );
      assert.equal(
        review.treatmentContext.length,
        expected === "context" ? 1 : 0,
        message,
      );
      assert.deepEqual(review.treatmentNotes, [], message);
    }
  }
});

